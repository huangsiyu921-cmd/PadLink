package com.padlink.core

/**
 * 重力转向的手感参数。
 *
 * 这几项**没有"正确值"**——手感取决于握姿、手机大小、玩什么游戏，只能自己试。
 * 所以做成数据而不是常量，界面上能调。
 */
data class TiltSettings(
    /** 这个角度以内不动。太大 → 初段肉；太小 → 手一抖摇杆就飘。 */
    val deadZoneDeg: Float = 1.5f,

    /** 推到这个角度算满舵。太小 → 稍微一动就打满，后段显得很冲；大一点余量才够。 */
    val maxAngleDeg: Float = 35f,

    /**
     * 曲线形状，作用在"死区之后"那段归一化行程上：
     *
     * - `1` 线性
     * - `< 1` 初段快、后端缓（0.5 约等于平方根的走势）—— 想"轻轻一倾就有反应"用这个
     * - `> 1` 初段慢、后端快 —— 想精细控方向、别一碰就偏用这个
     */
    val curve: Float = 0.75f,

    /** 低通系数。越小越平顺但越滞后；太大摇杆会跟着手的抖一起抖。 */
    val smoothing: Float = 0.25f,
)
